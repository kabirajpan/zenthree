use serde::{Deserialize, Serialize};

/// Dynamic model reported by the ACP agent.
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct AcpModel {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
}

/// Dynamic session mode reported by the ACP agent (e.g. "default", "yolo", "auto_edit").
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct AcpMode {
    pub id: String,
    pub name: String,
    pub description: Option<String>,
}

/// Slash command supported by the ACP agent in the current session (e.g. "/plan", "/logout").
#[derive(Clone, Debug, Deserialize, Serialize, PartialEq, Eq)]
pub struct AcpSlashCommand {
    pub name: String,
    pub description: String,
}

/// Streamed event emitted during prompt processing or session updates.
#[derive(Clone, Debug)]
pub enum AcpEvent {
    /// Incremental text delta generated by the agent.
    TextDelta(String),
    /// Incremental thought/reasoning delta (if provided by agent).
    ThoughtDelta(String),
    /// Notification of available slash commands for this session.
    AvailableCommands(Vec<AcpSlashCommand>),
    /// Notification of available session modes.
    ModesUpdated {
        current: String,
        available: Vec<AcpMode>,
    },
    /// Notification of available models.
    ModelsUpdated {
        current: String,
        available: Vec<AcpModel>,
    },
    /// The agent completed its turn.
    TurnCompleted {
        stop_reason: String,
    },
    /// An error occurred during communication.
    Error(String),
}
